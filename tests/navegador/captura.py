"""Recorrido adicional 2.2/2.3: guardado en todas las pestañas y recuperación offline."""
import asyncio, json, os
from pathlib import Path
from playwright.async_api import async_playwright, expect
from servidor_qa import FAMILIA,TOKEN
URL=os.environ["NORKA_URL"]
BASE=f"{URL}/familia/{FAMILIA}"
OUT=Path(os.environ["NORKA_QA_OUT"])
async def main():
    OUT.mkdir(parents=True,exist_ok=True)
    async with async_playwright() as p:
        browser=await p.chromium.launch()
        ctx=await browser.new_context(viewport={"width":360,"height":800},is_mobile=True,has_touch=True)
        await ctx.add_cookies([{"name":"norka_sesion","value":TOKEN,"url":URL,"httpOnly":True}])
        page=await ctx.new_page()
        errores=[]
        page.on("pageerror",lambda e:errores.append(str(e)))
        # La entrada principal debe llevar a la familia real, no a la muestra.
        await page.goto(URL+"/")
        await page.get_by_role("link",name="Entrar con mi cuenta",exact=True).click()
        await expect(page).to_have_url(URL+"/cuenta")
        await page.get_by_role("link",name="Mi familia",exact=True).click()
        await expect(page).to_have_url(BASE+"/hoy")
        # La muestra también ofrece acceso explícito a la cuenta real.
        await page.goto(URL+"/muestra/pantallas/hoy")
        await page.get_by_role("navigation",name="Navegación principal").get_by_role("button",name="Capturar",exact=True).click()
        await expect(page.get_by_role("dialog").get_by_text("Estás en la muestra visual.",exact=False)).to_be_visible()
        await page.get_by_role("dialog").get_by_role("link",name="Entrar con mi cuenta",exact=True).click()
        await expect(page).to_have_url(URL+"/cuenta")
        await page.get_by_role("link",name="Mi familia",exact=True).click()
        await expect(page).to_have_url(BASE+"/hoy")
        nav=page.get_by_role("navigation",name="Navegación principal")
        async def captura(texto):
            await nav.get_by_role("button",name="Capturar",exact=True).click()
            campo=page.get_by_role("textbox",name="Escribe lo que quieres recordar.")
            await expect(campo).to_be_visible()
            await campo.fill(texto)
            await page.get_by_role("button",name="Enviar",exact=True).click()
            await expect(page.get_by_role("dialog")).to_have_count(0)
        for nombre,ruta in [("Hoy","hoy"),("Familia",""),("Equilibrio","equilibrio"),("Actividad","actividad"),("Buscar","buscar")]:
            await page.goto(BASE+("/"+ruta if ruta else ""))
            await captura("QA "+nombre)
            await expect(page.get_by_text("Tu captura quedó guardada. Por revisar.",exact=True)).to_be_visible(timeout=20000)
        await page.goto(BASE+"/hoy")
        await ctx.set_offline(True)
        await captura("QA sin conexión")
        await expect(page.get_by_text("1 captura por enviar",exact=True)).to_be_visible()
        await ctx.set_offline(False)
        await expect(page.get_by_role("region",name="Por revisar").get_by_text("QA sin conexión",exact=True)).to_be_visible(timeout=25000)
        resultado=page.get_by_role("region",name="Resultado de captura")
        await expect(resultado).to_be_visible()
        await resultado.get_by_role("button",name="Editar",exact=True).click()
        await page.get_by_role("textbox",name="Título de la tarea").fill("QA editada")
        await page.get_by_role("button",name="Guardar",exact=True).click()
        await expect(resultado.get_by_text("QA editada",exact=True)).to_be_visible()
        await resultado.get_by_role("button",name="Deshacer",exact=True).click()
        await expect(resultado).to_have_count(0)
        await expect(page.get_by_text("QA editada",exact=True)).to_have_count(0)
        await captura("QA sin conexión")
        await expect(page.get_by_role("region",name="Por revisar").get_by_text("QA sin conexión",exact=True)).to_be_visible(timeout=25000)
        await page.reload()
        for nombre in ["Hoy","Familia","Equilibrio","Actividad","Buscar","sin conexión"]:
            await expect(page.get_by_text("QA "+nombre,exact=True)).to_have_count(1)
        # Edición de una captura anterior tras recargar (no depende de tarjeta transitoria).
        lista=page.get_by_role("region",name="Por revisar")
        await lista.get_by_role("button",name="Editar QA Hoy",exact=True).click()
        await page.get_by_role("textbox",name="Título de la tarea").fill("QA Hoy corregida")
        await page.get_by_role("button",name="Guardar",exact=True).click()
        await expect(lista.get_by_text("QA Hoy corregida",exact=True)).to_be_visible()
        await page.reload()
        await expect(lista.get_by_text("QA Hoy corregida",exact=True)).to_be_visible()
        await lista.get_by_role("button",name="Eliminar QA Hoy corregida",exact=True).click()
        await expect(page.get_by_role("dialog")).to_be_visible()
        await page.get_by_role("dialog").get_by_role("button",name="Eliminar",exact=True).click()
        await expect(lista.get_by_text("QA Hoy corregida",exact=True)).to_have_count(0)
        await expect(page.get_by_text("Captura deshecha",exact=True)).to_be_visible()
        await expect(page.get_by_text("Captura deshecha",exact=True)).to_have_count(0,timeout=8000)
        await page.reload()
        await expect(lista.get_by_text("QA Hoy corregida",exact=True)).to_have_count(0)
        await expect(lista.get_by_text("QA Familia",exact=True)).to_be_visible()
        # Deshacer disponible incluso tras perder la tarjeta de resultado al recargar.
        await captura("QA deshacer visible")
        await expect(lista.get_by_text("QA deshacer visible",exact=True)).to_be_visible()
        await page.reload()
        await lista.get_by_role("button",name="Deshacer QA deshacer visible",exact=True).click()
        await page.get_by_role("dialog").get_by_role("button",name="Eliminar",exact=True).click()
        await expect(lista.get_by_text("QA deshacer visible",exact=True)).to_have_count(0)
        # La cola anterior ya funcionaba con la página abierta; ahora comprobar recarga real sin red.
        await page.evaluate("navigator.serviceWorker.ready")
        await page.wait_for_function("!!navigator.serviceWorker.controller")
        await ctx.set_offline(True)
        await page.reload()
        await expect(page.get_by_role("heading",name="Sin conexión",exact=True)).to_be_visible()
        await page.get_by_role("textbox",name="Escribe lo que quieres recordar.").fill("QA recarga offline")
        await page.get_by_role("button",name="Guardar en este teléfono").click()
        await expect(page.get_by_text("1 captura por enviar",exact=True)).to_be_visible()
        await page.reload()
        await expect(page.get_by_text("1 captura por enviar",exact=True)).to_be_visible()
        # Una pestaña distinta no puede cargar contexto familiar ni capturar sin sesión previa.
        otra=await ctx.new_page()
        await otra.goto(BASE+"/hoy")
        await expect(otra.get_by_text("Conéctate a internet",exact=False)).to_be_visible()
        await expect(otra.get_by_role("button",name="Guardar en este teléfono")).to_have_count(0)
        await otra.close()
        await ctx.set_offline(False)
        await expect(page.get_by_role("region",name="Por revisar").get_by_text("QA recarga offline",exact=True)).to_have_count(1,timeout=25000)
        await page.reload()
        await expect(page.get_by_role("region",name="Por revisar").get_by_text("QA recarga offline",exact=True)).to_have_count(1,timeout=20000)
        await page.screenshot(path=str(OUT/"capturas-fase-2.png"),full_page=True)
        assert not errores,errores
        await browser.close()
    print("Captura: cinco destinos + desconexión + persistencia sin duplicados aprobadas")
    (OUT/"capturas-fase-2.json").write_text(json.dumps({"destinos":5,"offline":True,"persistencia":True,"errores":errores}))
asyncio.run(main())
