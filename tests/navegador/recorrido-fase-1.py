"""QA visual de la muestra, con Playwright y Chromium ya disponibles en el entorno.
No instala dependencias. NORKA_URL y NORKA_AXE indican el servidor y axe-core local.
Los datos introducidos son ejemplos y no llegan a Supabase.
"""
import asyncio, json, os
from pathlib import Path
from playwright.async_api import async_playwright, expect
URL=os.environ.get('NORKA_URL','http://localhost:3191')
AXE=os.environ.get('NORKA_AXE','/tmp/norka-axe.js')
OUT=Path('docs/fases/evidencia-1-9')
async def main():
 OUT.mkdir(parents=True,exist_ok=True)
 results={'rutas':[],'recorridos':[],'errores':[]}
 async with async_playwright() as p:
  browser=await p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  context=await browser.new_context(viewport={'width':360,'height':800},device_scale_factor=1,record_video_dir=str(OUT/'video'),record_video_size={'width':360,'height':800})
  page=await context.new_page()
  page.on('pageerror',lambda e:results['errores'].append(str(e)))
  async def axe(etiqueta):
   await page.add_script_tag(path=AXE)
   violations=await page.evaluate('async()=> (await axe.run(document,{runOnly:{type:"tag",values:["wcag2a","wcag2aa","wcag21aa"]}})).violations.map(v=>({id:v.id,impact:v.impact,nodos:v.nodes.map(n=>n.html)}))')
   assert not violations, (etiqueta,violations)
   ancho=await page.evaluate('document.documentElement.scrollWidth')
   assert ancho<=360,(etiqueta,ancho)
   results['rutas'].append({'vista':etiqueta,'violaciones':0,'ancho':ancho})
  for tema in ['oscuro','claro']:
   for route in ['','muestra/pantallas/hoy','muestra/pantallas/familia','muestra/pantallas/equilibrio','muestra/pantallas/actividad','muestra/pantallas/avisos','muestra/pantallas/buscar','muestra/pantallas/perfil']:
    await page.goto(URL+'/'+route)
    await page.evaluate('(t)=>document.documentElement.dataset.tema=t',tema)
    await page.evaluate('document.fonts.ready')
    await axe(tema+'/'+route)
    await page.screenshot(path=str(OUT/f'{route.split("/")[-1] or "entrada"}-{tema}-360.png'),full_page=True)
  await page.goto(URL+'/muestra/pantallas/hoy')
  nav=page.get_by_role('navigation',name='Navegación principal')
  await nav.get_by_role('link',name='Familia',exact=True).click()
  await expect(page.get_by_role('heading',name='Familia',exact=True)).to_be_visible()
  await page.get_by_role('button',name='Agregar persona',exact=True).click()
  dialog=page.get_by_role('dialog')
  await expect(dialog).to_be_visible()
  await dialog.get_by_label('Nombre o apodo',exact=True).fill('Emilia de prueba')
  await dialog.get_by_label('Día',exact=True).fill('31')
  await dialog.get_by_label('Mes',exact=True).select_option('2')
  await dialog.get_by_role('button',name='Guardar',exact=True).click()
  await expect(dialog.get_by_role('alert')).to_have_text('Revisa el día y el mes del cumpleaños.')
  await axe('hoja-persona-error')
  await dialog.get_by_label('Día',exact=True).fill('12')
  await dialog.get_by_label('Mes',exact=True).select_option('3')
  await dialog.get_by_role('button',name='Guardar',exact=True).click()
  await expect(page.get_by_role('dialog')).to_have_count(0)
  await expect(page.get_by_role('link',name='Emilia de prueba Sin plazos esta semana')).to_be_visible()
  await page.get_by_role('link',name='Emilia de prueba Sin plazos esta semana').click()
  await expect(page.get_by_role('heading',name='Emilia de prueba',exact=True)).to_be_visible()
  await page.get_by_role('button',name='Editar persona',exact=True).click()
  await dialog.get_by_label('Nombre o apodo',exact=True).fill('Emilia editada')
  await dialog.get_by_role('button',name='Guardar',exact=True).click()
  await expect(page.get_by_role('heading',name='Emilia editada',exact=True)).to_be_visible()
  await page.get_by_role('button',name='Archivar persona',exact=True).click()
  await dialog.get_by_role('button',name='Archivar persona',exact=True).click()
  await expect(page.get_by_role('heading',name='Familia',exact=True)).to_be_visible()
  await expect(page.get_by_role('link',name='Emilia editada Sin plazos esta semana')).to_have_count(0)
  await page.get_by_role('button',name='Deshacer',exact=True).click()
  await expect(page.get_by_role('link',name='Emilia editada Sin plazos esta semana')).to_be_visible()
  results['recorridos'].append('Crear, validar cumpleaños, editar, archivar y deshacer: aprobado')
  await page.get_by_role('link',name='El hogar Sin plazos esta semana').click()
  await expect(page.get_by_role('button',name='Archivar persona',exact=True)).to_have_count(0)
  results['recorridos'].append('El hogar no ofrece archivar: aprobado')
  await page.get_by_role('link',name='Buscar',exact=True).click()
  await page.get_by_role('searchbox').fill('emilia')
  await expect(page.get_by_role('link',name='Emilia editada',exact=True)).to_be_visible()
  await page.get_by_role('searchbox').fill('inexistente')
  await expect(page.get_by_text('No encontramos coincidencias.',exact=True)).to_be_visible()
  results['recorridos'].append('Búsqueda de muestra y estado sin resultados: aprobado')
  await nav.get_by_role('link',name='Familia',exact=True).click()
  await expect(page.get_by_role('heading',name='Familia',exact=True)).to_be_visible()
  await page.evaluate('window.scrollTo(0,48)')
  await page.wait_for_timeout(100)
  recogida=await page.locator('[class*="interfaz-module"]').first.count()
  valor=await page.evaluate('getComputedStyle(document.querySelector("main").parentElement).getPropertyValue("--recogida")')
  assert float(valor)==1,valor
  await page.screenshot(path=str(OUT/'cabecera-recogida-360.png'))
  await page.get_by_role('button',name='Ir al inicio',exact=True).click()
  await page.wait_for_timeout(500)
  assert await page.evaluate('window.scrollY')==0
  results['recorridos'].append('Cabecera ligada a desplazamiento 0–48 px y vuelta al inicio: aprobado')
  await page.get_by_role('button',name='Agregar persona',exact=True).click()
  await page.keyboard.press('Escape')
  await expect(dialog).to_have_count(0)
  await expect(page.get_by_role('button',name='Agregar persona',exact=True)).to_be_focused()
  results['recorridos'].append('Escape cierra y devuelve foco: aprobado')
  await nav.get_by_role('button',name='Capturar',exact=True).click()
  await expect(dialog.get_by_role('button',name='Enviar',exact=True)).to_be_disabled()
  await axe('captura-limite-explicito')
  await page.keyboard.press('Escape')
  await page.get_by_role('link',name='Perfil',exact=True).click()
  await page.get_by_label('Teléfono',exact=True).fill('1234')
  await page.get_by_role('button',name='Guardar',exact=True).click()
  await expect(page.locator('main').get_by_role('alert')).to_have_text('Faltan dígitos')
  await page.get_by_label('Teléfono',exact=True).fill('12345678')
  await page.get_by_role('button',name='Guardar',exact=True).click()
  await nav.get_by_role('link',name='Familia',exact=True).click()
  await page.get_by_role('link',name='Perfil',exact=True).click()
  await expect(page.get_by_label('Teléfono',exact=True)).to_have_value('1234 5678')
  results['recorridos'].append('Teléfono: valida 8 dígitos y conserva el borrador durante el recorrido: aprobado')
  await page.get_by_role('button',name='Claro',exact=True).first.click()
  assert await page.evaluate('document.documentElement.dataset.tema')=='claro'
  await nav.get_by_role('link',name='Hoy',exact=True).click()
  assert await page.evaluate('document.documentElement.dataset.tema')=='claro'
  results['recorridos'].append('Tema persistente durante la navegación: aprobado')
  for estado in ['Cargando','Error','Sin conexión','Vacío','Con datos']:
   details=page.locator('details')
   if not await details.evaluate('(el)=>el.open'): await page.get_by_text('Opciones de la muestra',exact=True).click()
   await details.get_by_role('button',name=estado,exact=True).click()
   await axe('estado-'+estado)
  results['recorridos'].append('Cinco controles de estado: aprobado; con datos conserva el alcance vacío de Hoy en fase 1')
  await page.emulate_media(reduced_motion='reduce')
  await nav.get_by_role('link',name='Equilibrio',exact=True).click()
  await expect(page.get_by_role('heading',name='Equilibrio',exact=True)).to_be_visible()
  await page.evaluate('''() => {
    for(const e of document.querySelectorAll('h1,h2,p,label,button,a,span,dt,dd,input,select,legend,summary')) {
      const size=parseFloat(getComputedStyle(e).fontSize); e.dataset.textSize=String(size);
    }
    for(const e of document.querySelectorAll('[data-text-size]')) e.style.fontSize=Number(e.dataset.textSize)*2+'px';
  }''')
  await axe('texto-200-movimiento-reducido')
  await page.screenshot(path=str(OUT/'equilibrio-texto-200-360.png'),full_page=True)
  results['recorridos'].append('Texto al 200 % y movimiento reducido: aprobado')
  await context.close(); await browser.close()
 assert not results['errores'],results['errores']
 (OUT/'resultados.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))
 print(json.dumps(results,ensure_ascii=False,indent=2))
asyncio.run(main())
